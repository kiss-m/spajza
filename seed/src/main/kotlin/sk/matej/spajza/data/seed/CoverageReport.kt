package sk.matej.spajza.data.seed

import sk.matej.spajza.domain.model.ComputedTag
import sk.matej.spajza.domain.model.Cuisine
import sk.matej.spajza.domain.model.MealType
import sk.matej.spajza.domain.model.NutritionSource
import sk.matej.spajza.domain.model.Recipe
import sk.matej.spajza.domain.model.RecipeTag
import java.io.File

/** Renders docs/CONTENT.md (coverage matrix) and docs/DATA_TODO.md (estimated nutrition). */
object CoverageReport {

    private val types: List<Pair<String, (Recipe) -> Boolean>> = listOf(
        "student" to { r -> RecipeTag.STUDENT in r.tags },
        "cheap" to { r -> ComputedTag.CHEAP in r.computedTags },
        "vegan" to { r -> ComputedTag.VEGAN in r.computedTags },
        "vegetarian" to { r -> ComputedTag.VEGETARIAN in r.computedTags },
        "high-protein" to { r -> ComputedTag.HIGH_PROTEIN in r.computedTags },
        "bulk" to { r -> ComputedTag.BULK in r.computedTags },
        "light" to { r -> ComputedTag.LIGHT in r.computedTags },
        "meal prep" to { r -> RecipeTag.MEAL_PREP in r.tags },
        "quick" to { r -> ComputedTag.QUICK in r.computedTags },
    )

    fun content(catalog: Catalog): String = buildString {
        val recipes = catalog.recipes
        val usda = catalog.ingredients.count { it.nutritionSource is NutritionSource.Usda }
        appendLine("# Catalog content coverage")
        appendLine()
        appendLine("Generated by `./gradlew :seed:contentReport` — do not edit by hand.")
        appendLine()
        appendLine("- Recipes: **${recipes.size}** (targets: Phase 1 → 150, Phase 2 → 400+, Phase 3 → 800+)")
        appendLine("- Ingredients: **${catalog.ingredients.size}** ($usda USDA FDC, ${catalog.ingredients.size - usda} estimates)")
        appendLine("- Substitutions: **${catalog.substitutions.size}**")
        appendLine()
        appendLine("## Cuisine × meal type")
        appendLine()
        table(
            header = listOf("Cuisine") + MealType.entries.map { it.name.lowercase() } + "total",
            rows = Cuisine.entries.map { cuisine ->
                val inCuisine = recipes.filter { it.cuisine == cuisine }
                listOf(cuisine.label()) + MealType.entries.map { meal -> inCuisine.count { meal in it.mealTypes }.cell() } +
                    inCuisine.size.cell()
            } + listOf(listOf("**total**") + MealType.entries.map { meal -> recipes.count { meal in it.mealTypes }.cell() } + recipes.size.cell()),
        )
        appendLine()
        appendLine("## Cuisine × type")
        appendLine()
        table(
            header = listOf("Cuisine") + types.map { it.first },
            rows = Cuisine.entries.map { cuisine ->
                val inCuisine = recipes.filter { it.cuisine == cuisine }
                listOf(cuisine.label()) + types.map { (_, matches) -> inCuisine.count(matches).cell() }
            } + listOf(listOf("**total**") + types.map { (_, matches) -> recipes.count(matches).cell() }),
        )
        appendLine()
        appendLine("## Meal type × type")
        appendLine()
        table(
            header = listOf("Meal type") + types.map { it.first },
            rows = MealType.entries.map { meal ->
                val ofMeal = recipes.filter { meal in it.mealTypes }
                listOf(meal.name.lowercase()) + types.map { (_, matches) -> ofMeal.count(matches).cell() }
            },
        )
    }

    fun dataTodo(catalog: Catalog): String = buildString {
        appendLine("# Data to-do")
        appendLine()
        appendLine("Generated by `./gradlew :seed:contentReport` — do not edit by hand.")
        appendLine()
        appendLine("## Estimated nutrition")
        appendLine()
        appendLine("These ingredients have no USDA FoodData Central match and use typical label values")
        appendLine("(source `estimate`). Replace them with better sources when available.")
        appendLine()
        val estimates = catalog.ingredients.filter { it.nutritionSource == NutritionSource.Estimate }.sortedBy { it.id }
        if (estimates.isEmpty()) {
            appendLine("None.")
        } else {
            table(
                header = listOf("Ingredient", "SK", "kcal", "protein", "carbs", "fat"),
                rows = estimates.map {
                    listOf("`${it.id}`", it.name.sk, it.nutrition.kcal.fmt(), it.nutrition.protein.fmt(), it.nutrition.carbs.fmt(), it.nutrition.fat.fmt())
                },
            )
        }
    }

    private fun StringBuilder.table(header: List<String>, rows: List<List<String>>) {
        appendLine(header.joinToString(" | ", "| ", " |"))
        appendLine(header.joinToString(" | ", "| ", " |") { "---" })
        rows.forEach { appendLine(it.joinToString(" | ", "| ", " |")) }
    }

    private fun Cuisine.label() = name.lowercase().replace('_', ' ')

    private fun Int.cell() = if (this == 0) "·" else toString()

    private fun Double.fmt() = if (this % 1.0 == 0.0) toLong().toString() else "%.1f".format(java.util.Locale.ROOT, this)

    /** Entry point of the `contentReport` Gradle task: `<seedDir> <docsDir>`. */
    @JvmStatic
    fun main(args: Array<String>) {
        val (seedDir, docsDir) = args.map(::File)
        val result = CatalogBuilder().build(SeedDirectory.read(seedDir))
        if (!result.isValid) System.err.println("Warning: seed has ${result.issues.size} issue(s); run :seed:test")
        File(docsDir, "CONTENT.md").writeText(content(result.catalog))
        File(docsDir, "DATA_TODO.md").writeText(dataTodo(result.catalog))
    }
}
